//! User contracts: the signed-in person's settings row and profile
//! (`/user/settings`, `/user/profile`).
//!
//! The gateway parses request bodies with these types and forwards what it
//! parsed, the core reads requests and builds responses with them, and the
//! TypeScript in `src/generated/user/` is generated from them (see
//! `tests/ts_bindings.rs`). Every response travels in `{ "data": … }`.
//!
//! The settings row carries a few documents the client writes whole
//! (`shortcuts`, `dashboard_layout`, `saved_views`, `inbox_state`) and a
//! free `preferences` object merged key by key. The documents are typed
//! here; they do not refuse unknown keys, because the core reads stored
//! rows with the same types and a row written by an older build must still
//! load. The request itself does refuse them.

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value as JsonValue};
use ts_rs::TS;
use utoipa::ToSchema;

use crate::Patch;

/// The colour scheme. `system` follows the operating system.
#[derive(
    Debug, Clone, Copy, Default, PartialEq, Eq, Hash, Serialize, Deserialize, ToSchema, TS,
)]
#[serde(rename_all = "lowercase")]
#[ts(export_to = "user/")]
pub enum Theme {
    Light,
    Dark,
    #[default]
    System,
}

/// How tightly rows and controls are packed. `compact` sets
/// `body.compact` in the web.
#[derive(
    Debug, Clone, Copy, Default, PartialEq, Eq, Hash, Serialize, Deserialize, ToSchema, TS,
)]
#[serde(rename_all = "lowercase")]
#[ts(export_to = "user/")]
pub enum Density {
    #[default]
    Cozy,
    Compact,
}

/// One widget's place on the customizable dashboard, in grid cells.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema, TS)]
#[ts(export_to = "user/")]
pub struct DashboardWidgetLayout {
    pub widget_id: String,
    pub x: i32,
    pub y: i32,
    pub cols: i32,
    pub rows: i32,
    pub visible: bool,
}

/// One saved view: a named filter set the user can come back to.
///
/// `filters` is the client's own filter model, stored verbatim: the server
/// keeps it without interpreting it.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema, TS)]
#[ts(export_to = "user/")]
pub struct SavedView {
    /// Stable id, generated by the client that created the view.
    pub id: String,
    pub name: String,
    #[serde(default)]
    #[ts(type = "Record<string, unknown>")]
    #[schema(value_type = Object)]
    pub filters: Map<String, JsonValue>,
    /// Grouping the view was saved with, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub group_by: Option<String>,
    /// RFC 3339. Empty for views stored before it was recorded.
    #[serde(default)]
    pub created_at: String,
}

/// What the user has dealt with in their inbox.
///
/// `seen_at` is a watermark (everything older counts as read) rather than
/// a list of ids, so "mark all read" does not grow without bound on a feed
/// that never stops. `archived` needs per-entry granularity and stays a
/// list.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, ToSchema, TS)]
#[ts(export_to = "user/")]
pub struct InboxState {
    /// RFC 3339. Absent means nothing has been marked read yet.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub seen_at: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub archived: Option<Vec<String>>,
    /// Entries opened one at a time since the watermark. Bounded, and
    /// emptied whenever the watermark moves past them.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub read: Option<Vec<String>>,
}

/// The settings row, as `GET` and `PUT /user/settings` answer it.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema, TS)]
#[ts(export_to = "user/")]
pub struct UserSettingsResponse {
    pub theme: Theme,
    /// An accent id; the web resolves an unknown one to its default.
    pub palette: String,
    pub language: String,
    pub density: Density,
    /// Free string settings, keyed by the client. `{}` when none.
    pub shortcuts: BTreeMap<String, String>,
    /// `null` until the user arranges their dashboard.
    pub dashboard_layout: Option<Vec<DashboardWidgetLayout>>,
    /// `[]` when the user has saved none.
    pub saved_views: Vec<SavedView>,
    pub inbox_state: InboxState,
    pub notifications_enabled: bool,
    pub email_notifications: bool,
    /// An IANA zone (`Europe/Berlin`); `null` = the browser's.
    pub timezone: Option<String>,
    /// The client's own preferences; `{}` until something is stored.
    #[ts(type = "Record<string, unknown>")]
    #[schema(value_type = Object)]
    pub preferences: Map<String, JsonValue>,
}

/// The most the merged `preferences` object may hold, serialised.
pub const USER_PREFERENCES_MAX_BYTES: usize = 16 * 1024;

/// A settings patch: `PUT /user/settings`.
///
/// Only the keys present are applied. A field that can be reset is a
/// [`Patch`]: absent = unchanged, `null` = back to the default (the
/// product's theme, palette, language, density and notification switches;
/// for `timezone` the browser's zone), a value = set. The documents
/// (`shortcuts`, `dashboard_layout`, `saved_views`, `inbox_state`) are
/// replaced whole; `preferences` is merged key by key, a `null` value
/// deleting that key, and at most [`USER_PREFERENCES_MAX_BYTES`] once
/// merged.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize, ToSchema, TS)]
#[serde(deny_unknown_fields)]
#[ts(export_to = "user/")]
pub struct UpdateUserSettingsRequest {
    #[serde(default, skip_serializing_if = "Patch::is_absent")]
    #[schema(value_type = Option<Theme>)]
    pub theme: Patch<Theme>,
    #[serde(default, skip_serializing_if = "Patch::is_absent")]
    #[schema(value_type = Option<String>)]
    pub palette: Patch<String>,
    #[serde(default, skip_serializing_if = "Patch::is_absent")]
    #[schema(value_type = Option<String>)]
    pub language: Patch<String>,
    #[serde(default, skip_serializing_if = "Patch::is_absent")]
    #[schema(value_type = Option<Density>)]
    pub density: Patch<Density>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub shortcuts: Option<BTreeMap<String, String>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub dashboard_layout: Option<Vec<DashboardWidgetLayout>>,
    /// Replaces the whole list. Views are read and written together, so
    /// there is no per-view endpoint to keep in sync.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub saved_views: Option<Vec<SavedView>>,
    /// Replaces the whole object, for the same reason as `saved_views`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub inbox_state: Option<InboxState>,
    #[serde(default, skip_serializing_if = "Patch::is_absent")]
    #[schema(value_type = Option<bool>)]
    pub notifications_enabled: Patch<bool>,
    #[serde(default, skip_serializing_if = "Patch::is_absent")]
    #[schema(value_type = Option<bool>)]
    pub email_notifications: Patch<bool>,
    /// An IANA zone (400 otherwise); `null` = back to the browser's.
    #[serde(default, skip_serializing_if = "Patch::is_absent")]
    #[schema(value_type = Option<String>)]
    pub timezone: Patch<String>,
    /// Merged key by key into the stored object: a key with a value sets
    /// it, a key with `null` deletes it, keys not sent stay.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional, type = "Record<string, unknown>")]
    #[schema(value_type = Option<Object>)]
    pub preferences: Option<Map<String, JsonValue>>,
}

/// The signed-in person, as `GET` and `PUT /user/profile` answer it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema, TS)]
#[ts(export_to = "user/")]
pub struct UserProfileResponse {
    pub id: String,
    pub email: String,
    pub display_name: String,
    /// `admin`, `operator`, `user` or `guest`.
    pub role: String,
    pub avatar_url: Option<String>,
    pub last_login_at: Option<String>,
    pub created_at: String,
}

/// `PUT /user/profile`. An absent (or `null`) name stays as it is.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, ToSchema, TS)]
#[serde(deny_unknown_fields)]
#[ts(export_to = "user/")]
pub struct UpdateProfileRequest {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub display_name: Option<String>,
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn a_settings_patch_tells_absent_from_null() {
        let req: UpdateUserSettingsRequest =
            serde_json::from_value(json!({ "theme": null, "timezone": "Europe/Berlin" }))
                .expect("patch");
        assert_eq!(req.theme, Patch::Null);
        assert_eq!(req.palette, Patch::Absent);
        assert_eq!(req.timezone, Patch::Value("Europe/Berlin".to_string()));
        assert_eq!(
            serde_json::to_value(&req).expect("serialise"),
            json!({ "theme": null, "timezone": "Europe/Berlin" })
        );
    }

    #[test]
    fn a_settings_patch_refuses_unknown_fields_and_bad_values() {
        for body in [
            json!({ "themes": "dark" }),
            json!({ "theme": "sepia" }),
            json!({ "density": "Compact" }),
            json!({ "shortcuts": { "a": 1 } }),
            json!({ "dashboard_layout": [{ "widget_id": "kpis", "visible": true }] }),
        ] {
            assert!(
                serde_json::from_value::<UpdateUserSettingsRequest>(body.clone()).is_err(),
                "{body}"
            );
        }
    }

    #[test]
    fn documents_read_rows_from_older_builds() {
        let view: SavedView =
            serde_json::from_value(json!({ "id": "v1", "name": "Mine", "pinned": true }))
                .expect("a view without filters or date");
        assert_eq!(view.filters, Map::new());
        assert_eq!(view.created_at, "");
        let state: InboxState =
            serde_json::from_value(json!({ "seen_at": "2026-10-17T00:00:00Z" })).expect("state");
        assert_eq!(state.archived, None);
        assert_eq!(
            serde_json::to_value(&state).expect("serialise"),
            json!({ "seen_at": "2026-10-17T00:00:00Z" })
        );
    }

    #[test]
    fn enums_travel_lower_case() {
        assert_eq!(
            serde_json::to_value(Theme::System).expect("theme"),
            json!("system")
        );
        assert_eq!(
            serde_json::to_value(Density::Compact).expect("density"),
            json!("compact")
        );
    }
}
